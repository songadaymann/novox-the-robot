"""Generate a C++ source file embedding the CMU dictionary (used by the CMake build).

Drops comments and alternate pronunciations, then splits the text into string
literals under 16 KB (MSVC's per-literal limit) so every compiler accepts it.

    python3 tools/embed_dict.py data/cmudict.dict build/generated/cmudict_embedded.cpp
"""
import sys

src, dst = sys.argv[1], sys.argv[2]
lines = []
with open(src, encoding="utf-8") as f:
    for line in f:
        line = line.split("#", 1)[0].strip()
        if not line or "(" in line.split(" ", 1)[0]:
            continue
        lines.append(line)
text = "\n".join(lines) + "\n"

chunks, cur = [], []
size = 0
for line in text.splitlines(keepends=True):
    if size + len(line) > 15000:
        chunks.append("".join(cur))
        cur, size = [], 0
    cur.append(line)
    size += len(line)
if cur:
    chunks.append("".join(cur))


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


with open(dst, "w", encoding="utf-8") as out:
    out.write("// Generated by tools/embed_dict.py from the CMU Pronouncing Dictionary\n")
    out.write("// (BSD-style license, see data/cmudict.LICENSE). Do not edit.\n")
    out.write("#include <cstddef>\n\nnamespace nvs {\n\n")
    out.write(f"extern const char* const kCmudictChunks[] = {{\n")
    for c in chunks:
        out.write("    " + lit(c) + ",\n")
    out.write("};\n")
    out.write(f"extern const size_t kCmudictChunkCount = {len(chunks)};\n\n}}  // namespace nvs\n")
print(f"{len(lines)} entries, {len(chunks)} chunks, {len(text) // 1024} KB -> {dst}")
